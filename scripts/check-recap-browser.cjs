const { chromium } = require('playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  try {
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${process.env.RECAP_BASE_URL || 'http://localhost:3000'}/luisferreira/recap`, { waitUntil: 'networkidle' })
    const stage = page.locator('main > div')
    const activeScene = () => stage.getAttribute('data-scene')
    const revealControls = () => page.mouse.move(1000, 100)
    const count = () => page.locator('h1 > span').first().innerText()

    async function checkPoster(id, movingElement) {
      await page.mouse.move(960, 540)
      await page.waitForTimeout(2200)
      assert.equal(await stage.getAttribute('data-controls'), 'hidden')
      assert.equal(await page.locator('[class*="utilities"]').evaluate(el => getComputedStyle(el).opacity), '0')
      assert.equal(await page.locator('[class*="progress"]').evaluate(el => getComputedStyle(el).opacity), '0')
      assert.equal(await page.getByRole('button', { name: 'Cena seguinte', exact: true }).locator('svg').evaluate(el => getComputedStyle(el).opacity), '0')
      const scene = page.getByRole('group', { name: id === 'opening' ? 'A abertura' : id === 'anticipation' ? 'O que vocês fizeram' : 'O alcance', exact: true })
      assert.equal(await scene.locator(':scope > div').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(8, 8, 10)')
      assert.equal(await page.locator('h1').evaluate(el => getComputedStyle(el).color), 'rgb(237, 237, 239)')
      const content = id === 'opening' ? page.locator('[class*="titleBlock"]') : page.locator('h1')
      const bounds = await content.boundingBox()
      assert.ok(Math.abs(bounds.x + bounds.width / 2 - 960) < 2, `${id} must be centred horizontally`)
      assert.ok(Math.abs(bounds.y + bounds.height / 2 - 540) < 2, `${id} must be centred vertically`)
      if (id !== 'opening') assert.equal(await page.locator('[aria-label="FarmeRRR"]').count(), 0, 'No permanent logo')
      await page.screenshot({ path: `.next/recap-${id}.png` })
      // Sample actual transforms after 20 seconds, not just animation declarations.
      await page.waitForTimeout(18000)
      assert.equal(await activeScene(), id, 'Scenes must never advance automatically')
      const element = page.locator(movingElement).first()
      const first = await element.evaluate(el => getComputedStyle(el).transform)
      await page.waitForTimeout(500)
      const second = await element.evaluate(el => getComputedStyle(el).transform)
      assert.notEqual(first, second, `${id} must still move after 20 seconds`)
    }

    assert.equal(await activeScene(), 'opening')
    assert.equal(await page.locator('h1').innerText(), 'MONTHLY RECAP')
    assert.match(await page.locator('[class*="edition"]').innerText(), /^[A-ZÇ]+ \d{4}$/)
    assert.equal(await page.locator('main').getByText(/DEMO|TU CONTROLAS|A COMUNIDADE|01\/03/).count(), 0)
    await checkPoster('opening', 'svg circle')

    await page.keyboard.press('Space')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowRight')
    await page.waitForTimeout(1300)
    assert.equal(await activeScene(), 'anticipation', 'Fast input must not skip anticipation')
    assert.equal(await page.locator('h1').innerText(), 'VOCÊS CLIPARAM.\nNÓS CONTÁMOS.')
    await checkPoster('anticipation', '[class*="ribbonLane"]')

    await page.keyboard.press('ArrowRight')
    await page.waitForTimeout(1150)
    const earlyCount = Number((await count()).replaceAll(' ', ''))
    await page.waitForTimeout(3000)
    const total = await count()
    assert.match(total, /^[\d ]+$/)
    assert.ok(earlyCount < Number(total.replaceAll(' ', '')))
    assert.equal(await page.locator('h1').getAttribute('aria-label'), `${total} views`)
    assert.equal(await page.locator('h1').innerText(), `${total}\nVIEWS`)
    await checkPoster('views', '[class*="burst"] > span > i')
    await page.keyboard.press('ArrowRight')
    assert.equal(await activeScene(), 'views')

    // Native focused button actions, fullscreen, edge clicks, replay and progress.
    await revealControls()
    await page.getByRole('button', { name: 'Rever início' }).click()
    await page.waitForTimeout(1100)
    assert.equal(await activeScene(), 'opening')
    await revealControls()
    await page.getByRole('button', { name: 'Alternar ecrã inteiro' }).click()
    assert.equal(await page.evaluate(() => Boolean(document.fullscreenElement)), true)
    await page.keyboard.press('Space')
    await page.waitForTimeout(300)
    assert.equal(await page.evaluate(() => Boolean(document.fullscreenElement)), false)
    assert.equal(await activeScene(), 'opening')
    await page.getByRole('button', { name: 'Cena seguinte', exact: true }).click()
    await page.waitForTimeout(1100)
    assert.equal(await activeScene(), 'anticipation')
    await page.getByRole('button', { name: 'Cena anterior', exact: true }).click()
    await page.waitForTimeout(1100)
    assert.equal(await activeScene(), 'opening')
    await revealControls()
    await page.getByRole('button', { name: 'O alcance', exact: true }).click()
    await page.waitForTimeout(1100)
    assert.equal(await activeScene(), 'views')
    await page.keyboard.press('ArrowLeft')
    await page.waitForTimeout(1100)
    assert.equal(await activeScene(), 'anticipation')

    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await page.locator('h1').innerText(), 'MONTHLY RECAP')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Space')
    assert.equal(await count(), total)
    assert.equal(await page.locator('main').evaluate(el => el.getAnimations({ subtree: true }).length), 0)
    await page.getByRole('button', { name: 'Rever início' }).focus()
    await page.keyboard.press('Space')
    assert.equal(await activeScene(), 'opening')
    await revealControls()
    await page.getByRole('button', { name: 'O alcance', exact: true }).click()

    for (const [width, height] of [[1366, 768], [1440, 900], [390, 844]]) {
      await page.setViewportSize({ width, height })
      // Chromium resolves dynamic viewport units on a subsequent rendering frame.
      await page.waitForFunction(() => document.documentElement.scrollHeight <= innerHeight, null, { timeout: 2000 })
      const box = await stage.boundingBox()
      assert.ok(Math.abs(box.width / box.height - 16 / 9) < .01)
      assert.equal(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight), false)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      const numberBox = await page.locator('h1 > span').first().boundingBox()
      assert.ok(numberBox.x >= box.x && numberBox.x + numberBox.width <= box.x + box.width + 1)
    }
    assert.deepEqual(errors, [])
    console.log('PASS: centred dark posters, white content, no permanent logo, controls hide, motion after 20 seconds, manual navigation, count, replay, fullscreen, focused Space, reduced motion, 16:9, no scrolling or browser errors.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
